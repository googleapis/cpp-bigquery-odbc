class ScopedEnvVar {
 public:
  ScopedEnvVar(char const* name, std::optional<std::string> const& value)
      : name_(name), previous_(::google::cloud::internal::GetEnv(name)) {
    SetEnv(name_, value);
  }
  ~ScopedEnvVar() { SetEnv(name_, previous_); }
  ScopedEnvVar(ScopedEnvVar const&) = delete;
  ScopedEnvVar& operator=(ScopedEnvVar const&) = delete;

 private:
  char const* name_;
  std::optional<std::string> previous_;
};

class ScopedTempJsonFile {
 public:
  explicit ScopedTempJsonFile(std::string const& contents) {
    static std::atomic<int> counter{0};
    auto filename =
        "odbc_bq_client_test_" + std::to_string(counter.fetch_add(1)) + ".json";
    path_ = (std::filesystem::temp_directory_path() / filename).string();
    std::ofstream out(path_, std::ios::binary | std::ios::trunc);
    out << contents;
  }
  ~ScopedTempJsonFile() {
    std::error_code ec;
    std::filesystem::remove(path_, ec);
  }
  [[nodiscard]] std::string const& path() const { return path_; }

 private:
  std::string path_;
};

