TEST(ODBCBQClient, CreateBQClientFailsWithInvalidCredentials) {
  auto odbc_bq_client =
      ODBCBQClient::CreateBQClient({OauthMechanism::kServiceAccount, ""});

  auto const expected_sql_state = odbc_internal::SQLStates::k_HY000();
  auto const expected_message =
      HasSubstr("The path to the file can't be empty");
  auto const expected_status =
      StatusRecordIs(expected_sql_state, expected_message);

  EXPECT_THAT(odbc_bq_client, expected_status);
}

TEST(ODBCBQClient, CreateBQClientValidatesUniverseDomainAndCredentials) {
  ScopedEnvVar clear_env_ud("GOOGLE_CLOUD_UNIVERSE_DOMAIN", std::nullopt);
  nlohmann::json tpc_sa = {
      {"type", "service_account"},
      {"project_id", "test-project"},
      {"private_key_id", "key-id"},
      {"private_key", MakeSyntheticPrivateKeyPem()},
      {"client_email", "sa@test-project.iam.gserviceaccount.com"},
      {"client_id", "123456789"},
      {"token_uri", "https://oauth2.s3nsapis.fr/token"},
      {"universe_domain", "s3nsapis.fr"},
  };
  ScopedTempJsonFile tpc_sa_file(tpc_sa.dump());

  // Malformed UniverseDomain fails with HY024 before credential loading.
  ConnProps bad_domain_props{OauthMechanism::kServiceAccount,
                             tpc_sa_file.path()};
  bad_domain_props.gcd.universe_domain = "https://s3nsapis.fr";
  EXPECT_THAT(ODBCBQClient::CreateBQClient(bad_domain_props),
              StatusRecordIs(odbc_internal::SQLStates::k_HY024(),
                             HasSubstr("Invalid UniverseDomain")));

  // EnableGCD=1 with empty UniverseDomain and no PSC fails with HY024.
  ConnProps empty_gcd_props{OauthMechanism::kServiceAccount,
                            tpc_sa_file.path()};
  empty_gcd_props.gcd.enable_gcd = true;
  EXPECT_THAT(ODBCBQClient::CreateBQClient(empty_gcd_props),
              StatusRecordIs(odbc_internal::SQLStates::k_HY024(),
                             HasSubstr("Invalid UniverseDomain")));

  // Omitting UniverseDomain with TPC credentials fails closed (28000) instead
  // of sending TPC tokens to googleapis.com.
  ConnProps missing_ud_props{OauthMechanism::kServiceAccount,
                             tpc_sa_file.path()};
  EXPECT_THAT(ODBCBQClient::CreateBQClient(missing_ud_props),
              StatusRecordIs(odbc_internal::SQLStates::k_28000(),
                             HasSubstr("does not match the universe domain")));

  // Matching UniverseDomain (even without EnableGCD=1, matching public docs)
  // succeeds.
  ConnProps matching_tpc_props{OauthMechanism::kServiceAccount,
                               tpc_sa_file.path()};
  matching_tpc_props.gcd.universe_domain = "s3nsapis.fr";
  ASSERT_STATUS_RECORD_OK(ODBCBQClient::CreateBQClient(matching_tpc_props));

  // Service account impersonation with matching TPC ServiceAccount succeeds.
  ConnProps imp_tpc_sa_props = matching_tpc_props;
  imp_tpc_sa_props.impersonated_email =
      "target@test-project.iam.gserviceaccount.com";
  ASSERT_STATUS_RECORD_OK(ODBCBQClient::CreateBQClient(imp_tpc_sa_props));

  // AuthorizedUser + impersonation in a non-default universe fails closed
  // because google-cloud-cpp v3.10.0 AuthorizedUserCredentials ignores
  // universe_domain when resolving REST IAM endpoints.
  nlohmann::json tpc_user = {
      {"type", "authorized_user"},        {"client_id", "cid"},
      {"client_secret", "csec"},          {"refresh_token", "rtok"},
      {"universe_domain", "s3nsapis.fr"},
  };
  ScopedTempJsonFile tpc_user_file(tpc_user.dump());
  ConnProps imp_tpc_user_props{OauthMechanism::kUserAccount,
                               tpc_user_file.path()};
  imp_tpc_user_props.gcd.universe_domain = "s3nsapis.fr";
  imp_tpc_user_props.impersonated_email =
      "target@test-project.iam.gserviceaccount.com";
  EXPECT_THAT(ODBCBQClient::CreateBQClient(imp_tpc_user_props),
              StatusRecordIs(
                  odbc_internal::SQLStates::k_28000(),
                  HasSubstr("do not support service account impersonation")));
}

